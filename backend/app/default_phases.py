PROFILE = '''
def 실행(카드):
    공개 = 카드.설정.get("개인서사공개", {})
    for 플레이어 in 플레이어들():
        if 플레이어.인물 is None:
            continue
        번호들 = 공개.get(str(플레이어.인물.순서), [1])
        내용 = 서사들(플레이어.인물, 번호들)
        플레이어.탭("개인 서사", 글("개인 서사", 내용))
        읽기(플레이어, "개인 서사", 내용)
'''

INTRO = '''
def 실행(카드):
    줄 = []
    for 플레이어 in 플레이어들():
        인물 = 플레이어.인물
        if 인물 is None:
            continue
        제목 = 인물.이름
        if 인물.직업:
            제목 = 제목 + " (" + 인물.직업 + ")"
        줄.append(제목 + " - " + 플레이어.이름)
        if 인물.소개:
            줄.append(인물.소개)
        줄.append("")
    모두.탭("자기소개", 글("자기소개", "\\n".join(줄)))
    모두.보이기(글("안내", "한 사람씩 자기소개를 해 주세요."))
'''

INVESTIGATE = '''
def 실행(카드):
    횟수 = 카드.설정.get("횟수", 3)
    남음 = {}
    for 플레이어 in 플레이어들():
        남음[플레이어.계정] = 횟수
        플레이어.탭("내 단서", 카드목록("내 단서", []))
        플레이어.보이기(현황("조사 횟수", 0, 횟수))
    모두.보이기(선택지("조사할 장소", 장소들(), 1, False))
    while True:
        받음 = 기다리기("확인")
        나 = 받음.플레이어
        if 남음[나.계정] <= 0:
            나.알림("조사 횟수를 모두 사용했습니다.")
            continue
        얻음 = 조사(나, 받음.값)
        if 얻음 is None:
            나.알림("이 장소에서는 더 얻을 것이 없습니다.")
            continue
        남음[나.계정] = 남음[나.계정] - 1
        나.탭("내 단서", 카드목록("내 단서", 보유목록(나)))
        나.보이기(글("조사 결과", 얻음["이름"] + ": " + 얻음["내용"]))
        나.보이기(현황("조사 횟수", 횟수 - 남음[나.계정], 횟수))
'''

DISCUSSION = '''
def 새로고침(동작들):
    for 플레이어 in 플레이어들():
        플레이어.탭("내 단서", 카드목록("내 단서", 보유목록(플레이어), 동작들))
        플레이어.탭("공개된 단서", 카드목록("공개된 단서", 받은공개(플레이어)))

def 실행(카드):
    동작들 = []
    if 카드.설정.get("보여주기허용", True):
        동작들.append("보여주기")
    if 카드.설정.get("양도허용", True):
        동작들.append("양도")
    새로고침(동작들)
    while True:
        받음 = 기다리기("내 단서")
        나 = 받음.플레이어
        값 = 받음.값
        if 값["동작"] == "보여주기":
            if not 공개설정(나, 값["단서"], 값["대상"]):
                나.알림("보여 줄 수 없는 단서입니다.")
        else:
            받는 = 값["대상"][0]
            if 양도(나, 받는, 값["단서"]):
                for 플레이어 in 플레이어들():
                    if 플레이어.계정 == 받는:
                        플레이어.알림(나.이름 + "님이 단서를 넘겨주었습니다.")
            else:
                나.알림("넘겨 줄 수 없는 단서입니다.")
        새로고침(동작들)
'''

