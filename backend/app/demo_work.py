class SeedError(Exception):
    pass


def _ok(res, expect=(200, 201)):
    if res.status_code not in expect:
        raise SeedError(f"{res.request.method} {res.request.url.path}: {res.status_code} {res.text}")
    return res.json() if res.content else None


def fixed_password() -> str:
    """환경변수 MM_SAMPLE_MAKER_PASSWORD 가 있으면 샘플 제작 계정의 패스워드로 쓴다(시연에서 제작 과정을 보여 주려고).
    없으면 빈 글자이고, 그 경우 패스워드는 무작위로 만들어 버려서 아무도 로그인할 수 없다."""
    return os.environ.get("MM_SAMPLE_MAKER_PASSWORD", "").strip()


MEDIA_EXT = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".mp4": "video/mp4"}


def attach_demo_media(client, headers, work_id: int, folder: Path, characters: dict[str, int], clues: dict[str, int]) -> list[str]:
    """`folder` 의 이미지·영상을 작품에 붙인다. 파일 이름으로 대상을 정한다(한글 이름은 맥의 분해형 글자도 같게 본다).

      인물-황칠성.jpg      그 이름의 인물에게 캐릭터 이미지
      단서-찢어진 편지.png  그 이름의 단서에게 이미지
      공통스토리.mp4        공통 스토리 영상
      표지.png              작품 표지 이미지(작품 목록과 플레이 기록에 보임)

    붙인 것과 붙이지 못한 것(이름이 없거나 형식이 맞지 않음)을 한 줄씩 돌려준다. 폴더가 없거나 비어 있으면 아무것도 하지 않는다."""
    if not folder.is_dir():
        return []
    lines = []
    for path in sorted(folder.iterdir()):
        mime = MEDIA_EXT.get(path.suffix.lower())
        stem = unicodedata.normalize("NFC", path.stem).strip()
        if not path.is_file() or path.name.startswith(".") or mime is None:
            continue                                         # README 같은 다른 파일은 건너뛴다
        if stem == "공통스토리":
            params = {"대상": "공통스토리"}
        elif stem == "표지":
            params = {"대상": "표지"}
        elif stem.startswith("인물-") and stem[3:].strip() in characters:
            params = {"대상": "인물", "번호": characters[stem[3:].strip()]}
        elif stem.startswith("단서-") and stem[3:].strip() in clues:
            params = {"대상": "단서", "번호": clues[stem[3:].strip()]}
        else:
            lines.append(f"건너뜀: {path.name} (맞는 인물·단서 이름이 없습니다)")
            continue
        res = client.put(f"/api/works/{work_id}/media", params=params, content=path.read_bytes(), headers={**headers, "Content-Type": mime})
        lines.append(f"붙임: {path.name}" if res.status_code == 201 else f"못 붙임: {path.name} ({res.status_code} {res.text[:120]})")
    return lines


def seed(client, conn=None) -> str:
    """샘플 작품을 만든다. 이미 있으면 "이미 있음", 만들었으면 "만듦"을 돌려준다. `client` 는 앱에 붙은 TestClient 이다.

    MM_SAMPLE_MAKER_PASSWORD 가 있으면 제작 계정(sample_maker)의 패스워드를 그 값으로 한다. 계정이 이미 있어도 그 값으로 맞춘다."""
    fixed = fixed_password()
    password = fixed or secrets.token_urlsafe(24)
    signup = client.post("/api/auth/signup", json={"아이디": MAKER_ID, "패스워드": password, "닉네임": MAKER_NICKNAME})
    if signup.status_code == 201:
        login = _ok(client.post("/api/auth/login", json={"아이디": MAKER_ID, "패스워드": password, "접속환경": "PC"}))
        headers = {"Authorization": f"Bearer {login['토큰']}"}
    else:
        if fixed:                                             # 이미 있는 계정도 고정 패스워드로 맞춘다(패스워드 찾기와 같은 방법: 아이디 + 닉네임)
            _ok(client.post("/api/auth/reset-password", json={"아이디": MAKER_ID, "닉네임": MAKER_NICKNAME, "새_패스워드": fixed}), expect=(204,))
        return "이미 있음"                                    # 샘플 계정이 이미 있으면 한 번 만든 것이다(고정 패스워드가 없으면 버렸으므로 다시 로그인하지 않는다)

    work = _ok(client.post("/api/works", headers=headers, json={
        "제목": TITLE, "시놉시스": SYNOPSIS, "장르": "추리", "예상시간": "15분", "시간형식": "시간만", "공통스토리": COMMON_STORY,
    }))
    wid = work["번호"]

    def post(path, **body):
        return _ok(client.post(f"/api/works/{wid}/{path}", headers=headers, json=body))

    char_order = {}
    for c in CHARACTERS:
        made = post("characters", 이름=c["이름"], 직업=c["직업"], 나이=c["나이"], 성별=c["성별"], 범인=c["범인"],
                    소개=c["소개"], 캐릭터설명=c["캐릭터설명"], 서사_부분=[{"ID": None, "본문": t} for t in c["서사"]],
                    타임라인=c["타임라인"], 비밀=c["비밀"], 목표=c["목표"])
        char_order[c["이름"]] = made["순서"]

    place_order = {name: post("content/places", 이름=name, 특징=text)["순서"] for name, text in PLACES}
    clue_order = {}
    for place, name, shown, text in CLUES:
        clue_order[name] = post("content/clues", 이름=name, 공개이름=shown, 내용=text, 장소_순서=place_order[place])["순서"]
    for place, name, shown, text in TESTIMONIES:
        post("content/testimonies", 이름=name, 공개이름=shown, 내용=text, 장소_순서=place_order[place])

    incident = post("content/incidents", 설명=INCIDENT)
    for start, end, text in TIMELINE:
        post("content/timelines", 시작시간=f"2000-01-01T{start}:00", 종료시간=f"2000-01-01T{end}:00", 설명=text)
    for name, condition, text in ENDINGS:
        post("content/endings", 이름=name, 조건=condition, 내용=text)
    for who, text in EPILOGUES:
        post("content/epilogues", 내용=text, **({"인물_순서": char_order[who]} if who else {}))

    library: dict[str, int] = {}
    for item in _ok(client.get("/api/library/phases", headers=headers)):      # 이름 순, 같은 이름은 최신 버전이 먼저 온다
        if item.get("계정_번호") is None:
            library.setdefault(item["이름"], item["번호"])
    for title, cards, minutes in PHASES:
        phase = post("content/phases", 이름=title, 진행시간=minutes)
        for name, settings in cards:
            if name not in library:
                raise SeedError(f"공통 진행단계 '{name}' 이 등록되어 있지 않습니다(register_common_phases 를 먼저 실행하세요)")
            post("content/phase-steps", 진행순서_순서=phase["순서"], 진행단계_번호=library[name], **({"설정": settings} if settings else {}))
    del incident

    folder = os.environ.get("MM_DEMO_MEDIA_DIR", "").strip()
    if folder:
        for line in attach_demo_media(client, headers, wid, Path(folder), char_order, clue_order):
            print("  " + line, flush=True)

    _ok(client.post(f"/api/works/{wid}/confirm", headers=headers, json={}))
    _ok(client.post(f"/api/works/{wid}/publish", headers=headers))
    return "만듦"
