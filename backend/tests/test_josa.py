"""조사 붙이기 (app/josa.py)."""
import pytest

from app.josa import attach


@pytest.mark.parametrize("word, pair, expected", [
    ("커터칼", "을/를", "커터칼을"), ("서랍", "을/를", "서랍을"), ("서랍 속 종이", "을/를", "서랍 속 종이를"),
    ("단서", "이/가", "단서가"), ("증언", "이/가", "증언이"), ("조합", "은/는", "조합은"), ("인물", "은/는", "인물은"),
    ("의사", "과/와", "의사와"), ("집사", "과/와", "집사와"), ("정원", "과/와", "정원과"),
    ("서재", "으로/로", "서재로"), ("정원", "으로/로", "정원으로"), ("서울", "으로/로", "서울로"),       # ㄹ 받침은 로
    ("범인", "이나/나", "범인이나"), ("의사", "이나/나", "의사나"),
    ("'서랍 속 종이'", "을/를", "'서랍 속 종이'를"), ("'독이 든 컵'", "을/를", "'독이 든 컵'을"),   # 따옴표·괄호는 건너뛴다
    ("버전 1.0", "을/를", "버전 1.0을"), ("버전 2", "을/를", "버전 2를"), ("서사 3", "이/가", "서사 3이"), ("서사 4", "이/가", "서사 4가"),
    ("NPC", "이/가", "NPC가"), ("NPC", "을/를", "NPC를"), ("PM", "을/를", "PM을"), ("ARL", "으로/로", "ARL로"),
    ("", "을/를", "를"),
])
def test_particle_follows_the_last_sound(word, pair, expected):
    assert attach(word, pair) == expected


def test_unknown_pair_is_refused():
    with pytest.raises(ValueError):
        attach("단서", "하고/랑")
