-- 기준: db/spec/schema_spec.xlsx (시트 '진행단계', '기믹')
--
-- 설계 (사용자 결정, 2026-10-15)
--  * 라이브러리 항목의 이름은 나중에 바꿀 수 있어야 한다. 이름이 계열(계정 + 이름)의 식별자이므로,
--    이름을 바꾸는 것은 **계열 전체(모든 버전)의 이름을 한꺼번에 바꾸는 것**이다.
--    DB 는 "삭제일시", "공개여부", "이름" 외의 수정을 계속 막는다. 계열의 모든 버전을 함께 바꾸는 일은
--    백엔드가 한 문장(UPDATE)으로 처리한다. 새 이름이 이미 있으면 (계정, 이름, 버전) 유일 제약이 거부한다.
--  * 작품은 라이브러리 항목을 "번호"로 가리키고 확정 스냅샷에는 값이 복사되므로 이름을 바꿔도 작품은 깨지지 않는다.
--  * 공통 진행단계 11개를 **시험용으로** 등록한다(계정_번호 NULL, 버전 1). "규칙"은 게임 규칙 형식이 정해지기 전이라 빈 값이다.
--    이후 운영자가 새 버전을 올리거나 삭제 표시를 해서 바꿀 수 있다.

CREATE OR REPLACE FUNCTION "fn_라이브러리_불변"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    -- 삭제일시·공개여부·이름을 제외한 나머지 컬럼은 바꿀 수 없다.
    IF (to_jsonb(NEW) - '삭제일시' - '공개여부' - '이름') IS DISTINCT FROM (to_jsonb(OLD) - '삭제일시' - '공개여부' - '이름') THEN
        RAISE EXCEPTION '"%"의 행은 수정할 수 없습니다. 같은 이름으로 버전을 올려 새 행을 추가하세요. (번호=%)',
            TG_TABLE_NAME, OLD."번호"
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    -- 삭제일시는 NULL 에서 값으로만 바꿀 수 있다. (삭제 취소·삭제 시각 변경 불가)
    IF NEW."삭제일시" IS DISTINCT FROM OLD."삭제일시" THEN
        IF OLD."삭제일시" IS NOT NULL OR NEW."삭제일시" IS NULL THEN
            RAISE EXCEPTION '"%"의 삭제 표시는 한 번만 할 수 있으며 되돌릴 수 없습니다. (번호=%)',
                TG_TABLE_NAME, OLD."번호"
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

